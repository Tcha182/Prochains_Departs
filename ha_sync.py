"""Keeps Home Assistant's heating history and dashboard in step with its valves.

Run by pi-system.sh, inside the Home Assistant container, with an access
token on stdin. For every thermostat it:
- writes the numeric sensors that give it long-term statistics, in
  /config/packages/chauffage_vannes.yaml (rechecked, and put back if refused);
- rebuilds the "Chauffage" dashboard: an overview, then one view per room.

A dashboard edited by hand is left alone: the script only replaces what it
wrote itself. Pass --adopt to take over an existing one.
"""

import asyncio
import hashlib
import json
import os
import re
import sys
import unicodedata

CONFIG_DIR = "/config"
PACKAGE_PATH = f"{CONFIG_DIR}/packages/chauffage_vannes.yaml"
HASH_PATH = f"{CONFIG_DIR}/packages/.chauffage_dashboard.sha256"
DASHBOARD_URL = "suivi-chauffage"
HA_WS = "ws://127.0.0.1:8123/api/websocket"

# The first two valves have their sensors in configuration.yaml, and their
# statistics are tied to these names.
LEGACY = {
    "climate.sonoff_trvzb_thermostat": "radiateur_1",
    "climate.sonoff_trvzb_thermostat_2": "radiateur_2",
}
OTHER_ROOM = "Autres"
OUTDOOR = "sensor.meteo_temperature"


def slug(text: str) -> str:
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "_", ascii_text.lower()).strip("_")


def sensor_prefix(entity_id: str) -> str:
    """radiateur_1, or radiateur_salon_escalier for climate.salon_escalier_thermostat."""
    if entity_id in LEGACY:
        return LEGACY[entity_id]
    name = entity_id.split(".", 1)[1]
    if name.endswith("_thermostat"):
        name = name[:-len("_thermostat")] or name
    return f"radiateur_{name}"


def list_valves(entities: list, devices: list, areas: list) -> list:
    """[{entity_id, name, room, prefix}] sorted by room, then name."""
    devices_by_id = {d["id"]: d for d in devices}
    area_names = {a["area_id"]: a["name"] for a in areas}
    valves = []
    for e in entities:
        entity_id = e["entity_id"]
        if not entity_id.startswith("climate.") or e.get("disabled_by"):
            continue
        device = devices_by_id.get(e.get("device_id")) or {}
        area = e.get("area_id") or device.get("area_id")
        valves.append({
            "entity_id": entity_id,
            "name": device.get("name_by_user") or device.get("name")
                    or e.get("name") or e.get("original_name") or entity_id,
            "room": area_names.get(area) or OTHER_ROOM,
            "prefix": sensor_prefix(entity_id),
        })
    valves.sort(key=lambda v: (v["room"] == OTHER_ROOM, v["room"].lower(),
                               v["name"].lower()))
    return valves


def _sensor(prefix, suffix, label, attr_state, availability, unit, device_class):
    lines = [
        f"      - name: {label}",
        f"        unique_id: {prefix}_{suffix}",
        f'        unit_of_measurement: "{unit}"',
    ]
    if device_class:
        lines.append(f"        device_class: {device_class}")
    lines += [
        "        state_class: measurement",
        f'        state: "{attr_state}"',
        f'        availability: "{availability}"',
    ]
    return lines


def build_package(valves: list) -> str:
    """YAML package with the sensors of the valves not in configuration.yaml."""
    new = [v for v in valves if v["entity_id"] not in LEGACY]
    head = ("# Generated by ha_sync.py (app repo): edits here are overwritten.\n"
            "# Numeric sensors so Home Assistant keeps statistics for each valve.\n")
    if not new:
        return head
    binary, sensors, history = [], [], []
    for v in new:
        eid, p = v["entity_id"], v["prefix"]
        label = "Radiateur " + p[len("radiateur_"):].replace("_", " ")
        binary += [
            f"      - name: {label} chauffe",
            f"        unique_id: {p}_chauffe",
            f"""        state: "{{{{ state_attr('{eid}', 'hvac_action') == 'heating' }}}}\"""",
            f"""        availability: "{{{{ has_value('{eid}') }}}}\"""",
        ]
        for suffix, word, attr in (("temperature", "temperature", "current_temperature"),
                                   ("consigne", "consigne", "temperature")):
            sensors += _sensor(
                p, suffix, f"{label} {word}",
                f"{{{{ state_attr('{eid}', '{attr}') }}}}",
                f"{{{{ state_attr('{eid}', '{attr}') is number }}}}",
                "°C", "temperature")
        sensors += _sensor(
            p, "part_de_chauffe", f"{label} part de chauffe",
            f"{{{{ 100 if is_state('binary_sensor.{p}_chauffe', 'on') else 0 }}}}",
            f"{{{{ has_value('binary_sensor.{p}_chauffe') }}}}",
            "%", None)
        history += [
            "  - platform: history_stats",
            f"    name: {label} chauffe aujourd hui",
            f"    unique_id: {p}_chauffe_aujourd_hui",
            f"    entity_id: binary_sensor.{p}_chauffe",
            '    state: "on"',
            "    type: time",
            '    start: "{{ today_at() }}"',
            '    end: "{{ now() }}"',
        ]
    return head + "\n".join([
        "template:", "  - binary_sensor:", *binary, "  - sensor:", *sensors,
        "", "sensor:", *history, "",
    ])


def _daily_temp(ids, title):
    return {"type": "statistics-graph", "title": title, "entities": ids,
            "period": "day", "days_to_show": 30,
            "stat_types": ["min", "mean", "max"], "chart_type": "line"}


def _daily_hours(ids, title):
    return {"type": "statistics-graph", "title": title, "entities": ids,
            "period": "day", "days_to_show": 30,
            "stat_types": ["max"], "chart_type": "bar"}


def build_dashboard(valves: list) -> dict:
    overview = [{"type": "thermostat", "entity": v["entity_id"], "name": v["name"]}
                for v in valves]
    overview += [
        {"type": "history-graph", "title": "48 dernières heures", "hours_to_show": 48,
         "entities": [{"entity": f"sensor.{v['prefix']}_temperature", "name": v["name"]}
                      for v in valves] + [{"entity": OUTDOOR, "name": "Extérieur"}]},
        _daily_temp([f"sensor.{v['prefix']}_temperature" for v in valves] + [OUTDOOR],
                    "Température par jour"),
        _daily_hours([f"sensor.{v['prefix']}_chauffe_aujourd_hui" for v in valves],
                     "Heures de chauffe par jour"),
    ]
    views = [{"title": "Vue d'ensemble", "path": "ensemble",
              "icon": "mdi:home-thermometer", "cards": overview}]
    rooms = {}
    for v in valves:
        rooms.setdefault(v["room"], []).append(v)
    for room, members in rooms.items():
        cards = []
        for v in members:
            p = v["prefix"]
            title = "" if len(members) == 1 else f" · {v['name']}"
            cards += [
                {"type": "thermostat", "entity": v["entity_id"], "name": v["name"]},
                {"type": "history-graph", "title": f"48 dernières heures{title}",
                 "hours_to_show": 48, "entities": [
                     {"entity": f"sensor.{p}_temperature", "name": "Température"},
                     {"entity": f"sensor.{p}_consigne", "name": "Consigne"},
                     {"entity": OUTDOOR, "name": "Extérieur"}]},
                _daily_temp([f"sensor.{p}_temperature"], f"Température par jour{title}"),
                _daily_hours([f"sensor.{p}_chauffe_aujourd_hui"],
                             f"Heures de chauffe par jour{title}"),
            ]
        views.append({"title": room, "path": slug(room).replace("_", "-"),
                      "icon": "mdi:radiator", "cards": cards})
    return {"title": "Chauffage", "views": views}


def config_hash(config: dict) -> str:
    text = json.dumps(config, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return None


def _write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


async def _sync(token: str, adopt: bool) -> int:
    import aiohttp  # only there inside Home Assistant

    if "packages:" not in (_read(f"{CONFIG_DIR}/configuration.yaml") or ""):
        print("configuration.yaml has no packages: entry, nothing done")
        return 1
    timeout = aiohttp.ClientTimeout(total=45)
    async with aiohttp.ClientSession(timeout=timeout) as session:
        async with session.ws_connect(HA_WS) as ws:
            await ws.receive_json()
            await ws.send_json({"type": "auth", "access_token": token})
            if (await ws.receive_json()).get("type") != "auth_ok":
                print("Home Assistant refused the token")
                return 2
            counter = 0

            async def call(**message):
                nonlocal counter
                counter += 1
                await ws.send_json({"id": counter, **message})
                while True:
                    reply = await ws.receive_json()
                    if reply.get("id") == counter:
                        return reply

            async def result(**message):
                reply = await call(**message)
                if not reply.get("success"):
                    raise RuntimeError(f"{message['type']}: {reply.get('error')}")
                return reply["result"]

            valves = list_valves(
                await result(type="config/entity_registry/list"),
                await result(type="config/device_registry/list"),
                await result(type="config/area_registry/list"))

            package = build_package(valves)
            previous = _read(PACKAGE_PATH)
            if package != previous:
                os.makedirs(os.path.dirname(PACKAGE_PATH), exist_ok=True)
                _write(PACKAGE_PATH, package)
                check_url = "http://127.0.0.1:8123/api/config/core/check_config"
                async with session.post(check_url, headers={
                        "Authorization": f"Bearer {token}"}) as resp:
                    check = await resp.json()
                if check.get("result") != "valid":
                    if previous is None:
                        os.remove(PACKAGE_PATH)
                    else:
                        _write(PACKAGE_PATH, previous)
                    print("generated sensors refused:", check.get("errors"))
                    return 3
                for domain in ("template", "history_stats"):
                    await call(type="call_service", domain=domain, service="reload")
                print("sensors updated")

            config = build_dashboard(valves)
            dashboards = await result(type="lovelace/dashboards/list")
            if not any(d.get("url_path") == DASHBOARD_URL for d in dashboards):
                await result(type="lovelace/dashboards/create", url_path=DASHBOARD_URL,
                             title="Chauffage", icon="mdi:radiator",
                             show_in_sidebar=True, require_admin=False, mode="storage")
                current = None
            else:
                reply = await call(type="lovelace/config", url_path=DASHBOARD_URL)
                current = reply.get("result") if reply.get("success") else None
            written = (_read(HASH_PATH) or "").strip()
            if current and not adopt and config_hash(current) != written:
                print("dashboard edited by hand, left alone")
                return 0
            if current != config:
                await result(type="lovelace/config/save", url_path=DASHBOARD_URL,
                             config=config)
                print("dashboard updated")
            _write(HASH_PATH, config_hash(config) + "\n")
            print("in sync:", ", ".join(f"{v['name']} ({v['room']})" for v in valves))
    return 0


def main() -> int:
    token = sys.stdin.readline().strip()
    if not token:
        print("no access token")
        return 2
    try:
        return asyncio.run(_sync(token, "--adopt" in sys.argv))
    except Exception as e:  # still starting, usually: the next run retries
        print(f"sync failed: {type(e).__name__}: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
